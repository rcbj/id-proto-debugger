function checkTableAndBackends() {
  log.debug("Entering checkTableAndBackends().");
  const ids = Object.keys(P.ALGORITHMS);
  ok(ids.length > 60, "ALGORITHMS has only " + ids.length + " rows");
  const kinds = ["digest", "mac", "kdf", "signature", "key-agreement",
                 "cipher", "key-wrap", "asym-encryption", "kem"];
  ids.forEach(function (id) {
    const row = P.ALGORITHMS[id];
    ok(row.id === id && kinds.indexOf(row.kind) >= 0 &&
       typeof row.deterministic === "boolean" && "keyType" in row,
       "ALGORITHMS row " + id + " is malformed");
  });
  // Every classical signature row is exercised by SIG_CASES.
  ids.filter(function (id) {
    const r = P.ALGORITHMS[id];
    return r.kind === "signature" && ["ec", "okp", "rsa"]
      .indexOf(r.keyType) >= 0;
  }).forEach(function (id) {
    ok(SIG_CASES.some(function (c) {
      return c.alg === id;
    }), "signature algorithm " + id + " is not cross-checked here");
  });
  ok(P.backend() === "js", "default backend is " + P.backend());
  ok(P.BACKENDS.join() === "js,webcrypto", "BACKENDS is " + P.BACKENDS);
  throwsLike(function () {
    P.setBackend("webcrypto");
  }, /no implementations/, "setBackend(webcrypto) did not refuse");
  throwsLike(function () {
    P.setBackend("openssl");
  }, /Unknown/, "setBackend(unknown) did not refuse");
  ok(P.backend() === "js", "a refused setBackend changed the backend");
  ok(typeof P.webcryptoAvailable() === "boolean",
     "webcryptoAvailable() is not a boolean");

  // A CERTIFICATE PEM yields its subject's public key. The certificate is
  // made with node-forge only because node cannot issue one.
  const forge = require("node-forge");
  const key = P.generateKeyPair("rsa-2048");
  const cert = forge.pki.createCertificate();
  cert.publicKey = forge.pki.publicKeyFromPem(P.exportKey(key, "spki-pem"));
  cert.serialNumber = "01";
  cert.validity.notBefore = new Date();
  cert.validity.notAfter = new Date(Date.now() + 86400000);
  cert.setSubject([{ name: "commonName", value: "provider test" }]);
  cert.setIssuer([{ name: "commonName", value: "provider test" }]);
  cert.sign(forge.pki.privateKeyFromPem(P.exportKey(key, "pkcs8-pem")),
            forge.md.sha256.create());
  const pem = forge.pki.certificateToPem(cert);
  eq(P.exportKey(P.importKey(pem), "spki-der"), P.exportKey(key, "spki-der"),
     "CERTIFICATE PEM import did not yield the subject's key");
  eq(new crypto.X509Certificate(pem).publicKey.export({ type: "spki",
     format: "der" }), P.exportKey(key, "spki-der"),
     "node reads a different key from the same certificate");
  log.debug("Leaving checkTableAndBackends().");
}

