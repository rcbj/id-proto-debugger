// ---------------------------------------------------------------------------
// common/crypto/crypto_provider.js — the one cryptography facade of issue
// #463 — driven in NODE with no browser, against an implementation that
// shares no code with it.
//
// The provider is built on @noble and node-forge. node's own `crypto` is
// OpenSSL, so every check here that compares the two is a check against a
// second, independent reading of the same specification:
//
//   * KEYS: every classical key type generated by the provider is exported as
//     SPKI and PKCS#8 DER, handed to node, and node's re-export must be
//     BYTE-IDENTICAL; node-generated keys imported by the provider must come
//     back out as the JWK node itself writes, and as node's own DER.
//   * SIGNATURES: for every classical signature algorithm, the provider
//     signs and node verifies, and node signs and the provider verifies —
//     ECDSA in both raw (r || s) and DER encodings.
//   * KEY AGREEMENT: ECDH / X25519 / X448 secrets equal node's
//     diffieHellman().
//   * DIGEST / HMAC / HKDF / PBKDF2 equal node's.
//   * AES-GCM, AES-CBC (padded and not), AES-KW, ChaCha20-Poly1305 and
//     RSA-OAEP / PKCS#1 v1.5 encryption interoperate with node in both
//     directions.
//
// and against the RFCs' own published values: RFC 7638's thumbprint, RFC
// 8037's Ed25519 key and signature, RFC 3394's key-wrap vectors, RFC 7518
// Appendix C's ECDH-ES Concat KDF output, and RFC 9052 Appendix C.7's
// COSE_Key. The post-quantum and hash-based pass-throughs are checked for
// shape and round trips — their bytes are tests/pqc_engines.js's and
// tests/hbs_signatures.js's business.
//
// Finally, the property the whole issue is about: the facade's source never
// names Web Crypto's `subtle`, so it works outside a secure context.
// ---------------------------------------------------------------------------

