const paths = require("./module_paths.js");
const CRYPTO_DIR = path.resolve(__dirname, "..", "common", "crypto");

function sourceOf(name) {
  log.debug("Entering sourceOf(). name=" + name);
  const candidates = paths.cryptoModuleCandidates
    ? paths.cryptoModuleCandidates(name)
    : [path.join(__dirname, name), path.join(CRYPTO_DIR, name)];
  for (const one of candidates) {
    if (fs.existsSync(one)) {
      log.debug("Leaving sourceOf().");
      return fs.readFileSync(one, "utf8");
    }
  }
  log.debug("Leaving sourceOf(). Not found.");
  throw new Error("could not locate " + name + " to read");
}

const P = paths.requireCryptoModule("crypto_provider.js");

// The fewest checks a healthy run makes. A refactor that silently drops a
// section (a loop over an emptied table, say) fails here rather than passing
// with less coverage.
const MIN_CHECKS = 1000;

var checks = 0;
var failures = [];

function ok(condition, message) {
  log.debug("Entering ok().");
  checks++;
  if (!condition) {
    failures.push(message);
    log.error("FAIL: " + message);
  }
  log.debug("Leaving ok().");
}

function eq(actual, expected, message) {
  log.debug("Entering eq().");
  ok(Buffer.from(actual).equals(Buffer.from(expected)),
     message + "\n  got      " + Buffer.from(actual).toString("hex") +
     "\n  expected " + Buffer.from(expected).toString("hex"));
  log.debug("Leaving eq().");
}

function throwsLike(fn, pattern, message) {
  log.debug("Entering throwsLike().");
  try {
    fn();
  } catch (e) {
    ok(pattern.test(e.message), message + " (threw: " + e.message + ")");
    log.debug("Leaving throwsLike().");
    return;
  }
  ok(false, message + " (did not throw)");
  log.debug("Leaving throwsLike().");
}

function section(name, fn) {
  log.debug("Entering section(). name=" + name);
  const before = checks;
  try {
    fn();
  } catch (e) {
    ok(false, "[" + name + "] threw: " + (e.stack || e.message));
  }
  log.info("[" + name + "] " + (checks - before) + " checks");
  log.debug("Leaving section().");
}

function hex(value) {
  log.debug("Entering hex().");
  log.debug("Leaving hex().");
  return Buffer.from(value).toString("hex");
}

function b64u(value) {
  log.debug("Entering b64u().");
  log.debug("Leaving b64u().");
  return Buffer.from(value).toString("base64url");
}

function sortedJson(object) {
  log.debug("Entering sortedJson().");
  const out = {};
  Object.keys(object).sort().forEach(function (k) {
    out[k] = object[k];
  });
  log.debug("Leaving sortedJson().");
  return JSON.stringify(out);
}

// The provider's key specs, with what node calls the same thing.
const CLASSICAL = [
  { spec: "ec-p256", node: ["ec", { namedCurve: "P-256" }] },
  { spec: "ec-p384", node: ["ec", { namedCurve: "P-384" }] },
  { spec: "ec-p521", node: ["ec", { namedCurve: "P-521" }] },
  { spec: "ec-secp256k1", node: ["ec", { namedCurve: "secp256k1" }] },
  { spec: "ed25519", node: ["ed25519", {}] },
  { spec: "ed448", node: ["ed448", {}] },
  { spec: "x25519", node: ["x25519", {}] },
  { spec: "x448", node: ["x448", {}] },
  { spec: "rsa-2048", node: ["rsa", { modulusLength: 2048 }] },
  { spec: "rsa-3072", node: ["rsa", { modulusLength: 3072 }] }
];

function nodePublic(der) {
  log.debug("Entering nodePublic().");
  log.debug("Leaving nodePublic().");
  return crypto.createPublicKey({ key: Buffer.from(der), format: "der",
                                  type: "spki" });
}

function nodePrivate(der) {
  log.debug("Entering nodePrivate().");
  log.debug("Leaving nodePrivate().");
  return crypto.createPrivateKey({ key: Buffer.from(der), format: "der",
                                   type: "pkcs8" });
}

// ---------------------------------------------------------------------------
// 1. No Web Crypto, no DOM.
// ---------------------------------------------------------------------------
function checkSourceRules() {
  log.debug("Entering checkSourceRules().");
  ["crypto_provider.js", "crypto_keys.js"].forEach(function (name) {
    const src = sourceOf(name);
    ok(src.indexOf("subtle") < 0,
       name + " names `subtle`. The facade is pure JS (issue #463): Web " +
       "Crypto is at most an optional second backend, and never in this " +
       "file.");
    const forbidden = /\b(document|window|localStorage|sessionStorage)\s*\./;
    const domLines = [];
    src.split(/\r?\n/).forEach(function (line, index) {
      const code = line.replace(/^\s*(\/\/|\*).*$/, "");
      if (forbidden.test(code)) {
        domLines.push((index + 1) + ": " + line.trim());
      }
    });
    ok(domLines.length === 0, name + " touches the DOM:\n  " +
       domLines.join("\n  "));
    // Staged FLAT into client/src for the bundles, so a sibling must be
    // required as ./name and nothing may reach up or down a directory.
    const requires = src.match(/require\("[^"]+"\)/g) || [];
    requires.forEach(function (r) {
      ok(!/require\("\.\.?\/[^"]*\//.test(r),
         name + " has a nested relative require " + r + "; files in " +
         "common/crypto are staged flat into client/src.");
    });
  });
  log.debug("Leaving checkSourceRules().");
}

// ---------------------------------------------------------------------------
// 2. Generated here -> node: SPKI and PKCS#8 byte-identical.
// ---------------------------------------------------------------------------
function checkGeneratedKeysAgainstNode() {
  log.debug("Entering checkGeneratedKeysAgainstNode().");
  CLASSICAL.forEach(function (c) {
    const key = P.generateKeyPair(c.spec);
    const spki = P.exportKey(key, "spki-der");
    const pkcs8 = P.exportKey(key, "pkcs8-der");
    const np = nodePublic(spki);
    const nk = nodePrivate(pkcs8);
    eq(np.export({ type: "spki", format: "der" }), spki,
       c.spec + ": node's SPKI re-export differs from ours");
    eq(nk.export({ type: "pkcs8", format: "der" }), pkcs8,
       c.spec + ": node's PKCS#8 re-export differs from ours");
    ok(sortedJson(nk.export({ format: "jwk" })) ===
       sortedJson(P.exportKey(key, "jwk")),
       c.spec + ": node's JWK of our key differs from our JWK");
    // PEM framing is the same bytes.
    ok(P.exportKey(key, "spki-pem") ===
       np.export({ type: "spki", format: "pem" }),
       c.spec + ": SPKI PEM differs from node's");
    ok(P.exportKey(key, "pkcs8-pem") ===
       nk.export({ type: "pkcs8", format: "pem" }),
       c.spec + ": PKCS#8 PEM differs from node's");
    if (c.spec.indexOf("rsa") === 0) {
      ok(key.bits === c.node[1].modulusLength,
         c.spec + ": bits is " + key.bits);
    }
  });
  log.debug("Leaving checkGeneratedKeysAgainstNode().");
}

// ---------------------------------------------------------------------------
// 3. Generated by node -> imported here, every input format.
// ---------------------------------------------------------------------------
function checkNodeKeysImported() {
  log.debug("Entering checkNodeKeysImported().");
  CLASSICAL.forEach(function (c) {
    const pair = crypto.generateKeyPairSync(c.node[0], c.node[1]);
    const nodeJwk = pair.privateKey.export({ format: "jwk" });
    const nodePubJwk = pair.publicKey.export({ format: "jwk" });
    const p8 = pair.privateKey.export({ type: "pkcs8", format: "der" });
    const spki = pair.publicKey.export({ type: "spki", format: "der" });

    const fromP8 = P.importKey(p8, { format: "pkcs8-der" });
    ok(sortedJson(P.exportKey(fromP8, "jwk")) === sortedJson(nodeJwk),
       c.spec + ": PKCS#8 import -> JWK differs from node's JWK");
    eq(P.exportKey(fromP8, "pkcs8-der"), p8,
       c.spec + ": PKCS#8 import -> export is not node's DER");
    eq(P.exportKey(fromP8, "spki-der"), spki,
       c.spec + ": public half of an imported PKCS#8 is not node's SPKI");

    const fromSpki = P.importKey(spki, { format: "spki-der" });
    ok(sortedJson(P.exportKey(fromSpki, "jwk")) === sortedJson(nodePubJwk),
       c.spec + ": SPKI import -> JWK differs from node's public JWK");
    ok(!fromSpki.privateKey, c.spec + ": an SPKI import has a private key");

    const fromPem = P.importKey(pair.privateKey.export({ type: "pkcs8",
                                                         format: "pem" }));
    eq(P.exportKey(fromPem, "pkcs8-der"), p8, c.spec + ": PEM import");
    const fromPubPem = P.importKey(pair.publicKey.export({ type: "spki",
                                                           format: "pem" }));
    eq(P.exportKey(fromPubPem, "spki-der"), spki, c.spec + ": PUBLIC KEY PEM");

    const fromJwk = P.importKey(nodeJwk);
    eq(P.exportKey(fromJwk, "pkcs8-der"), p8,
       c.spec + ": JWK import -> PKCS#8 is not node's DER");
    const fromJson = P.importKey(JSON.stringify(nodePubJwk));
    eq(P.exportKey(fromJson, "spki-der"), spki,
       c.spec + ": JWK text import -> SPKI is not node's DER");

    // The legacy PEMs: PKCS#1 for RSA and SEC 1 for EC.
    if (c.node[0] === "rsa") {
      const pk1 = pair.privateKey.export({ type: "pkcs1", format: "pem" });
      eq(P.exportKey(P.importKey(pk1), "pkcs8-der"), p8,
         c.spec + ": RSA PRIVATE KEY PEM import");
      const pub1 = pair.publicKey.export({ type: "pkcs1", format: "pem" });
      eq(P.exportKey(P.importKey(pub1), "spki-der"), spki,
         c.spec + ": RSA PUBLIC KEY PEM import");
      eq(P.exportKey(fromP8, "raw", { private: true }),
         pair.privateKey.export({ type: "pkcs1", format: "der" }),
         c.spec + ": raw RSA private is not PKCS#1 DER");
      eq(P.exportKey(fromP8, "raw"),
         pair.publicKey.export({ type: "pkcs1", format: "der" }),
         c.spec + ": raw RSA public is not PKCS#1 DER");
    }
    if (c.node[0] === "ec") {
      const sec1 = pair.privateKey.export({ type: "sec1", format: "pem" });
      eq(P.exportKey(P.importKey(sec1), "pkcs8-der"), p8,
         c.spec + ": EC PRIVATE KEY (SEC 1) PEM import");
    }
  });
  log.debug("Leaving checkNodeKeysImported().");
}

// ---------------------------------------------------------------------------
// 4. Raw and compressed forms.
// ---------------------------------------------------------------------------
function checkRawForms() {
  log.debug("Entering checkRawForms().");
  ["ec-p256", "ec-p384", "ec-p521", "ec-secp256k1"].forEach(function (spec) {
    const key = P.generateKeyPair(spec);
    const raw = P.exportKey(key, "raw");
    ok(raw[0] === 4, spec + ": raw public is not an uncompressed point");
    const back = P.importKey(raw, { format: "raw", type: spec });
    eq(back.publicKey, key.publicKey, spec + ": raw public round trip");
    // Compressed: 02/03 || X. The provider must decompress to the same key.
    const size = (raw.length - 1) / 2;
    const compressed = Buffer.concat([
      Buffer.from([raw[raw.length - 1] & 1 ? 3 : 2]),
      Buffer.from(raw.slice(1, 1 + size))]);
    eq(P.importKey(compressed, { format: "raw", type: spec }).publicKey,
       key.publicKey, spec + ": compressed point import");
    const priv = P.importKey(P.exportKey(key, "raw", { private: true }),
                             { format: "raw", type: spec, private: true });
    eq(priv.publicKey, key.publicKey,
       spec + ": raw private import derives a different public key");
    // An off-curve point is refused, not imported.
    const bad = Buffer.from(raw);
    bad[bad.length - 1] ^= 1;
    throwsLike(function () {
      P.importKey(bad, { format: "raw", type: spec });
    }, /./, spec + ": an off-curve point was accepted");
  });
  ["ed25519", "ed448", "x25519", "x448"].forEach(function (spec) {
    const key = P.generateKeyPair(spec);
    const priv = P.importKey(P.exportKey(key, "raw", { private: true }),
                             { format: "raw", type: spec, private: true });
    eq(priv.publicKey, key.publicKey, spec + ": raw private -> public");
    eq(P.importKey(P.exportKey(key, "raw"), { format: "raw",
                                              type: spec }).publicKey,
       key.publicKey, spec + ": raw public round trip");
  });
  // A JWK whose halves disagree is refused.
  const a = P.exportKey(P.generateKeyPair("ec-p256"), "jwk");
  const b = P.exportKey(P.generateKeyPair("ec-p256"), "jwk");
  throwsLike(function () {
    P.importKey({ kty: "EC", crv: "P-256", x: a.x, y: a.y, d: b.d });
  }, /does not belong/, "a JWK with a foreign d was accepted");
  log.debug("Leaving checkRawForms().");
}

// ---------------------------------------------------------------------------
// 5. Signatures, both directions, every classical algorithm.
// ---------------------------------------------------------------------------
const SIG_CASES = [
  { alg: "ecdsa-p256-sha256", spec: "ec-p256", hash: "sha256", ecdsa: true },
  { alg: "ecdsa-p384-sha384", spec: "ec-p384", hash: "sha384", ecdsa: true },
  { alg: "ecdsa-p521-sha512", spec: "ec-p521", hash: "sha512", ecdsa: true },
  { alg: "ecdsa-secp256k1-sha256", spec: "ec-secp256k1", hash: "sha256",
    ecdsa: true },
  { alg: "rsa-pkcs1-sha1", spec: "rsa-2048", hash: "sha1" },
  { alg: "rsa-pkcs1-sha256", spec: "rsa-2048", hash: "sha256" },
  { alg: "rsa-pkcs1-sha384", spec: "rsa-2048", hash: "sha384" },
  { alg: "rsa-pkcs1-sha512", spec: "rsa-2048", hash: "sha512" },
  { alg: "rsa-pss-sha256", spec: "rsa-2048", hash: "sha256", pss: true },
  { alg: "rsa-pss-sha384", spec: "rsa-2048", hash: "sha384", pss: true },
  { alg: "rsa-pss-sha512", spec: "rsa-2048", hash: "sha512", pss: true },
  { alg: "ed25519", spec: "ed25519", hash: null },
  { alg: "ed448", spec: "ed448", hash: null }
];

function nodeSignOpts(c, keyObject, encoding) {
  log.debug("Entering nodeSignOpts().");
  const o = { key: keyObject };
  if (c.ecdsa) {
    o.dsaEncoding = encoding === "der" ? "der" : "ieee-p1363";
  }
  if (c.pss) {
    o.padding = crypto.constants.RSA_PKCS1_PSS_PADDING;
    o.saltLength = crypto.constants.RSA_PSS_SALTLEN_DIGEST;
  }
  log.debug("Leaving nodeSignOpts().");
  return o;
}

function checkSignatures() {
  log.debug("Entering checkSignatures().");
  const keyCache = {};
  const message = Buffer.from("The quick brown fox jumps over the lazy dog");
  const other = Buffer.from("The quick brown fox jumps over the lazy cog");
  SIG_CASES.forEach(function (c) {
    if (!keyCache[c.spec]) {
      keyCache[c.spec] = P.generateKeyPair(c.spec);
    }
    const key = keyCache[c.spec];
    const pub = P.publicKeyOf(key);
    const nodePriv = nodePrivate(P.exportKey(key, "pkcs8-der"));
    const nodePub = nodePublic(P.exportKey(key, "spki-der"));
    const encodings = c.ecdsa ? ["raw", "der"] : ["raw"];
    encodings.forEach(function (enc) {
      const label = c.alg + (c.ecdsa ? " (" + enc + ")" : "");
      for (let round = 0; round < 3; round++) {
        const msg = Buffer.concat([message, Buffer.from([round])]);
        const ours = P.sign(c.alg, key, msg, { encoding: enc });
        ok(crypto.verify(c.hash, msg, nodeSignOpts(c, nodePub, enc), ours),
           label + ": node does not verify our signature");
        ok(P.verify(c.alg, pub, msg, ours, { encoding: enc }),
           label + ": we do not verify our own signature");
        const theirs = crypto.sign(c.hash, msg, nodeSignOpts(c, nodePriv, enc));
        ok(P.verify(c.alg, pub, msg, theirs, { encoding: enc }),
           label + ": we do not verify node's signature");
      }
      const sig = P.sign(c.alg, key, message, { encoding: enc });
      ok(!P.verify(c.alg, pub, other, sig, { encoding: enc }),
         label + ": a signature verified over a different message");
      const tampered = Buffer.from(sig);
      tampered[tampered.length - 2] ^= 0x40;
      ok(!P.verify(c.alg, pub, message, tampered, { encoding: enc }),
         label + ": a tampered signature verified");
      ok(P.verify(c.alg, pub, message, new Uint8Array(3),
                  { encoding: enc }) === false,
         label + ": a garbage signature did not return false");
    });
    if (c.ecdsa) {
      // RFC 6979: the js backend's ECDSA is deterministic.
      eq(P.sign(c.alg, key, message), P.sign(c.alg, key, message),
         c.alg + ": ECDSA signing is not deterministic");
      // raw <-> DER helpers agree with what node writes.
      const size = (key.publicKey.length - 1) / 2;
      for (let i = 0; i < 4; i++) {
        const der = crypto.sign(c.hash, message, nodeSignOpts(c, nodePriv,
                                                              "der"));
        const raw = P.derToRawEcdsa(der, size);
        eq(P.rawToDerEcdsa(raw), der,
           c.alg + ": rawToDerEcdsa(derToRawEcdsa(node DER)) is not " +
           "node's DER");
        ok(crypto.verify(c.hash, message, nodeSignOpts(c, nodePub, "raw"),
                         Buffer.from(raw)),
           c.alg + ": derToRawEcdsa output does not verify in node");
      }
    }
  });
  // P-521's DER SEQUENCE exceeds 127 bytes, so its length is LONG FORM —
  // the case @noble/curves 1.4.0's own DER writer gets wrong.
  const p521 = keyCache["ec-p521"];
  let sawLongForm = false;
  for (let i = 0; i < 8 && !sawLongForm; i++) {
    const der = P.sign("ecdsa-p521-sha512", p521, Buffer.from([i]),
                       { encoding: "der" });
    if (der[1] === 0x81) {
      sawLongForm = true;
      ok(crypto.verify("sha512", Buffer.from([i]),
         { key: nodePublic(P.exportKey(p521, "spki-der")) }, der),
         "a long-form P-521 DER signature does not verify in node");
    }
  }
  ok(sawLongForm, "no P-521 DER signature with a long-form length was seen");

  // HIGH-S is accepted on secp256k1, where @noble refuses it by default.
  const k1 = keyCache["ec-secp256k1"];
  const n = BigInt("0xfffffffffffffffffffffffffffffffebaaedce6af48a03bbfd25e" +
                   "8cd0364141");
  const low = P.sign("ecdsa-secp256k1-sha256", k1, message);
  const s = BigInt("0x" + hex(low.slice(32)));
  const high = Buffer.concat([Buffer.from(low.slice(0, 32)),
    Buffer.from((n - s).toString(16).padStart(64, "0"), "hex")]);
  ok(crypto.verify("sha256", message, { key: nodePublic(P.exportKey(k1,
     "spki-der")), dsaEncoding: "ieee-p1363" }, high),
     "node does not accept the high-S twin (test setup)");
  ok(P.verify("ecdsa-secp256k1-sha256", k1, message, high),
     "a valid high-S secp256k1 signature was refused");

  // Wrong key types are the CALLER's bug and throw.
  throwsLike(function () {
    P.sign("ecdsa-p256-sha256", keyCache["ec-p384"], message);
  }, /P-256/, "ES256 with a P-384 key did not throw");
  throwsLike(function () {
    P.sign("ed25519", P.publicKeyOf(keyCache["ed25519"]), message);
  }, /PUBLIC key/, "signing with a public key did not throw");
  log.debug("Leaving checkSignatures().");
}

// ---------------------------------------------------------------------------
// 6. Key agreement.
// ---------------------------------------------------------------------------
function checkEcdh() {
  log.debug("Entering checkEcdh().");
  ["ec-p256", "ec-p384", "ec-p521", "ec-secp256k1", "x25519",
   "x448"].forEach(function (spec) {
    for (let i = 0; i < 3; i++) {
      const a = P.generateKeyPair(spec);
      const b = P.generateKeyPair(spec);
      const z = P.ecdh(a, P.publicKeyOf(b));
      eq(z, P.ecdh(b, P.publicKeyOf(a)), spec + ": ECDH is not symmetric");
      const nodeZ = crypto.diffieHellman({
        privateKey: nodePrivate(P.exportKey(a, "pkcs8-der")),
        publicKey: nodePublic(P.exportKey(b, "spki-der")) });
      eq(z, nodeZ, spec + ": shared secret differs from node's");
    }
  });
  // An all-zero X25519 output (small-order peer) is refused.
  const a = P.generateKeyPair("x25519");
  throwsLike(function () {
    P.ecdh(a, P.importKey(new Uint8Array(32), { format: "raw",
                                                type: "x25519" }));
  }, /small order|Invalid/,
  "X25519 with the zero point was not refused");
  throwsLike(function () {
    P.ecdh(a, P.publicKeyOf(P.generateKeyPair("x448")));
  }, /same curve/, "ECDH across curves did not throw");
  log.debug("Leaving checkEcdh().");
}

// ---------------------------------------------------------------------------
// 7. Digests, MACs, KDFs.
// ---------------------------------------------------------------------------
function checkDigestsAndKdfs() {
  log.debug("Entering checkDigestsAndKdfs().");
  const inputs = [Buffer.alloc(0), Buffer.from("abc"),
                  crypto.randomBytes(200)];
  const names = { sha1: "sha1", sha224: "sha224", sha256: "sha256",
                  sha384: "sha384", sha512: "sha512",
                  "sha512-256": "sha512-256", "sha3-256": "sha3-256",
                  "sha3-384": "sha3-384", "sha3-512": "sha3-512" };
  Object.keys(names).forEach(function (alg) {
    inputs.forEach(function (input) {
      eq(P.digest(alg, input), crypto.createHash(names[alg]).update(input)
         .digest(), alg + " digest differs from node's");
      const key = crypto.randomBytes(37);
      eq(P.hmac(alg, key, input),
         crypto.createHmac(names[alg], key).update(input).digest(),
         "hmac-" + alg + " differs from node's");
    });
  });
  const k = crypto.randomBytes(32);
  ok(P.hmacVerify("hmac-sha256", k, "x", P.hmac("sha256", k, "x")),
     "hmacVerify refused a good tag");
  ok(!P.hmacVerify("hmac-sha256", k, "y", P.hmac("sha256", k, "x")),
     "hmacVerify accepted a wrong tag");
  // An oct key works where bytes do.
  const oct = P.importKey({ kty: "oct", k: b64u(k) });
  eq(P.hmac("sha384", oct, "m"), crypto.createHmac("sha384", k).update("m")
     .digest(), "hmac with an oct key");
  // A string is UTF-8 text, never an empty array.
  eq(P.digest("sha256", "abc \u2713"), crypto.createHash("sha256")
     .update("abc \u2713", "utf8").digest(), "a string digests as UTF-8");

  ["sha256", "sha384", "sha512", "sha1"].forEach(function (alg) {
    [16, 32, 42, 100].forEach(function (len) {
      const ikm = crypto.randomBytes(22);
      const salt = crypto.randomBytes(13);
      const info = crypto.randomBytes(10);
      eq(P.hkdf(alg, ikm, salt, info, len),
         Buffer.from(crypto.hkdfSync(alg, ikm, salt, info, len)),
         "hkdf-" + alg + " length " + len + " differs from node's");
      eq(P.pbkdf2(alg, "password", salt, 1000, len),
         crypto.pbkdf2Sync("password", salt, 1000, len, alg),
         "pbkdf2-" + alg + " length " + len + " differs from node's");
    });
  });
  // RFC 5869 test case 1 (SHA-256).
  eq(P.hkdf("sha256", Buffer.from("0b".repeat(22), "hex"),
            Buffer.from("000102030405060708090a0b0c", "hex"),
            Buffer.from("f0f1f2f3f4f5f6f7f8f9", "hex"), 42),
     Buffer.from("3cb25f25faacd57a90434f64d0362f2a2d2d0a90cf1a5a4c5db02d56" +
                 "ecc4c5bf34007208d5b887185865", "hex"),
     "RFC 5869 test case 1");
  // KMAC against SP 800-185's KMAC sample #1.
  eq(P.kmac("kmac128", Buffer.from("404142434445464748494a4b4c4d4e4f5051" +
                                   "52535455565758595a5b5c5d5e5f", "hex"),
            Buffer.from("00010203", "hex"), { outputBits: 256 }),
     Buffer.from("e5780b0d3ea6f7d3a429c5706aa43a00fadbd7d49628839e3187243f" +
                 "456ee14e", "hex"),
     "SP 800-185 KMAC128 sample #1");

  // Concat KDF: re-derived from SP 800-56A with node's hash, then RFC 7518
  // Appendix C's ECDH-ES example end to end.
  [16, 32, 48, 80].forEach(function (len) {
    const z = crypto.randomBytes(32);
    const other = crypto.randomBytes(20);
    let expected = Buffer.alloc(0);
    for (let i = 1; expected.length < len; i++) {
      const counter = Buffer.alloc(4);
      counter.writeUInt32BE(i);
      expected = Buffer.concat([expected, crypto.createHash("sha256")
        .update(Buffer.concat([counter, z, other])).digest()]);
    }
    eq(P.concatKdf("sha256", z, len, other), expected.subarray(0, len),
       "concat KDF length " + len);
  });
  const alice = P.importKey({ kty: "EC", crv: "P-256",
    x: "gI0GAILBdu7T53akrFmMyGcsF3n5dO7MmwNBHKW5SV0",
    y: "SLW_xSffzlPWrHEVI30DHM_4egVwt3NQqeUD7nMFpps",
    d: "0_NxaRPUMQoAJt50Gz8YiTr8gRTwyEaCumd-MToTmIo" });
  const bob = P.importKey({ kty: "EC", crv: "P-256",
    x: "weNJy2HscCSM6AEDTDg04biOvhFhyyWvOHQfeF_PxMQ",
    y: "e8lnCO-AlStT-NJVX-crhB7QRYhiix03illJOVAOyck",
    d: "VEmDZpDXXK8p8N0Cndsxs924q6nS1RXFASRl6BfUqdw" });
  const z = P.ecdh(alice, P.publicKeyOf(bob));
  function lenPrefixed(buf) {
    log.debug("Entering lenPrefixed().");
    const l = Buffer.alloc(4);
    l.writeUInt32BE(buf.length);
    log.debug("Leaving lenPrefixed().");
    return Buffer.concat([l, buf]);
  }
  const suppPub = Buffer.alloc(4);
  suppPub.writeUInt32BE(128);
  const otherInfo = Buffer.concat([lenPrefixed(Buffer.from("A128GCM")),
    lenPrefixed(Buffer.from("Alice")), lenPrefixed(Buffer.from("Bob")),
    suppPub]);
  ok(b64u(P.concatKdf("sha256", z, 16, otherInfo)) ===
     "VqqN6vgjbSBcIijNcacQGg", "RFC 7518 Appendix C ECDH-ES derived key");
  log.debug("Leaving checkDigestsAndKdfs().");
}

// ---------------------------------------------------------------------------
// 8. Symmetric ciphers and key wrap, both directions against node.
// ---------------------------------------------------------------------------
function checkSymmetric() {
  log.debug("Entering checkSymmetric().");
  [16, 24, 32].forEach(function (klen) {
    const bits = klen * 8;
    [0, 1, 15, 16, 33, 100].forEach(function (plen) {
      const key = crypto.randomBytes(klen);
      const pt = crypto.randomBytes(plen);
      // GCM
      const iv12 = crypto.randomBytes(12);
      const aad = crypto.randomBytes(plen % 7);
      const ours = P.aesGcmEncrypt(key, iv12, pt, aad);
      const dec = crypto.createDecipheriv("aes-" + bits + "-gcm", key, iv12);
      dec.setAAD(aad);
      dec.setAuthTag(Buffer.from(ours.tag));
      eq(Buffer.concat([dec.update(ours.ciphertext), dec.final()]), pt,
         "AES-" + bits + "-GCM: node cannot decrypt ours");
      const enc = crypto.createCipheriv("aes-" + bits + "-gcm", key, iv12);
      enc.setAAD(aad);
      const ct = Buffer.concat([enc.update(pt), enc.final()]);
      eq(ours.ciphertext, ct, "AES-" + bits + "-GCM ciphertext differs");
      eq(ours.tag, enc.getAuthTag(), "AES-" + bits + "-GCM tag differs");
      eq(P.aesGcmDecrypt(key, iv12, ct, enc.getAuthTag(), aad), pt,
         "AES-" + bits + "-GCM: we cannot decrypt node's");
      // CBC, PKCS#7
      const iv16 = crypto.randomBytes(16);
      const cbc = crypto.createCipheriv("aes-" + bits + "-cbc", key, iv16);
      const cbcCt = Buffer.concat([cbc.update(pt), cbc.final()]);
      eq(P.aesCbcEncrypt(key, iv16, pt), cbcCt,
         "AES-" + bits + "-CBC (PKCS#7) ciphertext differs from node's");
      eq(P.aesCbcDecrypt(key, iv16, cbcCt), pt,
         "AES-" + bits + "-CBC (PKCS#7): we cannot decrypt node's");
      // CBC, no padding (whole blocks)
      const whole = crypto.randomBytes(16 * (1 + (plen % 4)));
      const raw = crypto.createCipheriv("aes-" + bits + "-cbc", key, iv16);
      raw.setAutoPadding(false);
      const rawCt = Buffer.concat([raw.update(whole), raw.final()]);
      eq(P.aesCbcEncrypt(key, iv16, whole, { padding: "none" }), rawCt,
         "AES-" + bits + "-CBC (unpadded) differs from node's");
      eq(P.aesCbcDecrypt(key, iv16, rawCt, { padding: "none" }), whole,
         "AES-" + bits + "-CBC (unpadded): we cannot decrypt node's");
    });
    // GCM authentication failure throws.
    const key = crypto.randomBytes(klen);
    const iv = crypto.randomBytes(12);
    const sealed = P.aesGcmEncrypt(key, iv, Buffer.from("secret"), null);
    const bad = Buffer.from(sealed.tag);
    bad[0] ^= 1;
    throwsLike(function () {
      P.aesGcmDecrypt(key, iv, sealed.ciphertext, bad, null);
    }, /./, "AES-GCM accepted a modified tag");
    // AES-KW against node's id-aesNNN-wrap.
    [16, 24, 32, 40, 64].forEach(function (dlen) {
      const kek = crypto.randomBytes(klen);
      const data = crypto.randomBytes(dlen);
      const w = crypto.createCipheriv("id-aes" + bits + "-wrap", kek,
        Buffer.from("A6A6A6A6A6A6A6A6", "hex"));
      const nodeWrapped = Buffer.concat([w.update(data), w.final()]);
      eq(P.aesKwWrap(kek, data), nodeWrapped,
         "AES-KW " + bits + " / " + dlen + " bytes differs from node's");
      eq(P.aesKwUnwrap(kek, nodeWrapped), data,
         "AES-KW " + bits + ": we cannot unwrap node's");
      const tampered = Buffer.from(nodeWrapped);
      tampered[5] ^= 1;
      throwsLike(function () {
        P.aesKwUnwrap(kek, tampered);
      }, /integrity/, "AES-KW " + bits + ": a tampered key unwrapped");
    });
  });
  // RFC 3394 section 4's own vectors.
  const KW = [
    ["000102030405060708090A0B0C0D0E0F", "00112233445566778899AABBCCDDEEFF",
     "1FA68B0A8112B447AEF34BD8FB5A7B829D3E862371D2CFE5"],
    ["000102030405060708090A0B0C0D0E0F1011121314151617",
     "00112233445566778899AABBCCDDEEFF",
     "96778B25AE6CA435F92B5B97C050AED2468AB8A17AD84E5D"],
    ["000102030405060708090A0B0C0D0E0F101112131415161718191A1B1C1D1E1F",
     "00112233445566778899AABBCCDDEEFF",
     "64E8C3F9CE0F5BA263E9777905818A2A93C8191E7D6E8AE7"],
    ["000102030405060708090A0B0C0D0E0F101112131415161718191A1B1C1D1E1F",
     "00112233445566778899AABBCCDDEEFF000102030405060708090A0B0C0D0E0F",
     "28C9F404C4B810F4CBCCB35CFB87F8263F5786E2D80ED326CBC7F0E71A99F43B" +
     "FB988B9B7A02DD21"]
  ];
  KW.forEach(function (v, i) {
    eq(P.aesKwWrap(Buffer.from(v[0], "hex"), Buffer.from(v[1], "hex")),
       Buffer.from(v[2], "hex"), "RFC 3394 vector " + (i + 1) + " wrap");
    eq(P.aesKwUnwrap(Buffer.from(v[0], "hex"), Buffer.from(v[2], "hex")),
       Buffer.from(v[1], "hex"), "RFC 3394 vector " + (i + 1) + " unwrap");
  });
  // ChaCha20-Poly1305 against node.
  for (let i = 0; i < 4; i++) {
    const key = crypto.randomBytes(32);
    const nonce = crypto.randomBytes(12);
    const pt = crypto.randomBytes(i * 37);
    const aad = crypto.randomBytes(i * 3);
    const c = crypto.createCipheriv("chacha20-poly1305", key, nonce,
                                    { authTagLength: 16 });
    c.setAAD(aad, { plaintextLength: pt.length });
    const ct = Buffer.concat([c.update(pt), c.final()]);
    const ours = P.chacha20Poly1305Encrypt(key, nonce, pt, aad);
    eq(ours.ciphertext, ct, "ChaCha20-Poly1305 ciphertext differs");
    eq(ours.tag, c.getAuthTag(), "ChaCha20-Poly1305 tag differs");
    eq(P.chacha20Poly1305Decrypt(key, nonce, ct, c.getAuthTag(), aad), pt,
       "ChaCha20-Poly1305: we cannot decrypt node's");
  }
  log.debug("Leaving checkSymmetric().");
}

// ---------------------------------------------------------------------------
// 9. RSA encryption.
// ---------------------------------------------------------------------------
function checkRsaEncryption() {
  log.debug("Entering checkRsaEncryption().");
  const key = P.generateKeyPair("rsa-2048");
  const nodePriv = nodePrivate(P.exportKey(key, "pkcs8-der"));
  const nodePub = nodePublic(P.exportKey(key, "spki-der"));
  [["rsa-oaep-sha1", "sha1"], ["rsa-oaep-sha256", "sha256"]]
    .forEach(function (pair) {
      for (let i = 0; i < 3; i++) {
        const pt = crypto.randomBytes(16 + i * 8);
        const ours = P.rsaEncrypt(pair[0], P.publicKeyOf(key), pt);
        eq(crypto.privateDecrypt({ key: nodePriv, oaepHash: pair[1],
          padding: crypto.constants.RSA_PKCS1_OAEP_PADDING },
          Buffer.from(ours)), pt, pair[0] + ": node cannot decrypt ours");
        const theirs = crypto.publicEncrypt({ key: nodePub, oaepHash: pair[1],
          padding: crypto.constants.RSA_PKCS1_OAEP_PADDING }, pt);
        eq(P.rsaDecrypt(pair[0], key, theirs), pt,
           pair[0] + ": we cannot decrypt node's");
      }
    });
  // PKCS#1 v1.5: node 22 refuses to DECRYPT it (CVE-2023-46809, the Marvin
  // attack) but still encrypts, so the cross-check is one way plus a round
  // trip.
  for (let i = 0; i < 3; i++) {
    const pt = crypto.randomBytes(24);
    const theirs = crypto.publicEncrypt({ key: nodePub,
      padding: crypto.constants.RSA_PKCS1_PADDING }, pt);
    eq(P.rsaDecrypt("rsa-pkcs1v15-enc", key, theirs), pt,
       "RSA PKCS#1 v1.5: we cannot decrypt node's");
    eq(P.rsaDecrypt("rsa-pkcs1v15-enc", key,
                    P.rsaEncrypt("rsa-pkcs1v15-enc", key, pt)), pt,
       "RSA PKCS#1 v1.5 round trip");
  }
  log.debug("Leaving checkRsaEncryption().");
}

